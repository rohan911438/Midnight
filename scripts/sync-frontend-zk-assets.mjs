#!/usr/bin/env node
// Prepares the frontend for browser-side circuit calls (frontend/lib/contract.ts):
//
// 1. Copies the compiled contract's prover/verifier keys and ZK IR into
//    frontend/public so the browser can fetch them at runtime (via
//    FetchZkConfigProvider). contracts/build/ is the source of truth
//    (committed to the repo); this is a build-time copy.
// 2. Writes frontend/.env.local with NEXT_PUBLIC_CONTRACT_ADDRESS and
//    NEXT_PUBLIC_NETWORK_ID derived from the root .env, so the deployed
//    contract address only has to be recorded in one place. Next.js only
//    reads .env files from the app's own root, not the monorepo root.
//
// Run automatically before `npm run frontend` / `frontend`'s own build
// (see frontend/package.json's predev/prebuild scripts).
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import dotenv from 'dotenv';

const rootDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const buildDir = path.join(rootDir, 'contracts', 'build');
const frontendDir = path.join(rootDir, 'frontend');
const publicDir = path.join(frontendDir, 'public');

if (!existsSync(buildDir)) {
  console.error(`contracts/build not found -- run "npm run compile-contract" first (looked in ${buildDir})`);
  process.exit(1);
}

for (const dir of ['keys', 'zkir']) {
  const src = path.join(buildDir, dir);
  const dest = path.join(publicDir, dir);
  mkdirSync(dest, { recursive: true });
  cpSync(src, dest, { recursive: true });
  console.log(`Copied ${src} -> ${dest}`);
}

const rootEnvPath = path.join(rootDir, '.env');
const rootEnv = existsSync(rootEnvPath) ? dotenv.parse(readFileSync(rootEnvPath, 'utf8')) : {};
const envLocalPath = path.join(frontendDir, '.env.local');
const envLocalContents = [
  '# Generated by scripts/sync-frontend-zk-assets.mjs from the root .env -- do not edit by hand.',
  `NEXT_PUBLIC_NETWORK_ID=${rootEnv.NETWORK_ID ?? 'preview'}`,
  `NEXT_PUBLIC_CONTRACT_ADDRESS=${rootEnv.CONTRACT_ADDRESS ?? ''}`,
  '',
].join('\n');
writeFileSync(envLocalPath, envLocalContents, 'utf8');
console.log(`Wrote ${envLocalPath}`);
